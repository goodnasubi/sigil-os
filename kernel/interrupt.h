#ifndef SIGIL_OS_INTERRUPT_H
#define SIGIL_OS_INTERRUPT_H

#include <stdint.h>

#define IDT_ENTRIES 256
#define TEST_INTERRUPT_VECTOR 0x20

struct idt_gate {
    uint16_t offset_low;
    uint16_t selector;
    uint8_t ist;
    uint8_t type_attr;
    uint16_t offset_mid;
    uint32_t offset_high;
    uint32_t reserved;
} __attribute__((packed));

struct idt_ptr {
    uint16_t limit;
    uint64_t base;
} __attribute__((packed));

struct isr_regs {
    uint64_t r15;
    uint64_t r14;
    uint64_t r13;
    uint64_t r12;
    uint64_t r11;
    uint64_t r10;
    uint64_t r9;
    uint64_t r8;
    uint64_t rdi;
    uint64_t rsi;
    uint64_t rbp;
    uint64_t rbx;
    uint64_t rdx;
    uint64_t rcx;
    uint64_t rax;
    uint64_t vector;
    uint64_t error_code;
    uint64_t rip;
    uint64_t cs;
    uint64_t rflags;
    uint64_t rsp;
    uint64_t ss;
};

void interrupt_init(void);
void test_interrupt_receive(void);
uint64_t interrupt_get_count(void);
uint64_t interrupt_get_last_vector(void);

void interrupt_dispatch(struct isr_regs *regs);

#endif
